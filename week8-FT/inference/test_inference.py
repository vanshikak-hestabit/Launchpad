import time
import torch
import pandas as pd
import os
from transformers import AutoTokenizer, AutoModelForCausalLM
from llama_cpp import Llama
from sentence_transformers import SentenceTransformer, util

BASE_MODEL = "TinyLlama/TinyLlama-1.1B-Chat-v1.0"
FT_MODEL = "./merged_model"
GGUF_MODEL = "./model-q8_0.gguf"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
RESULTS_PATH = "./benchmarks/results.csv"

PROMPTS = [
    "What is Addison's disease?",
    "What causes hypertension.",
    "What is the function of the hippocampus?"
]

GROUND_TRUTH = [
    "A disorder where the adrenal glands do not produce enough cortisol and aldosterone, causing fatigue, weight loss, low blood pressure, and skin darkening.",
    "Hypertension, or high blood pressure, is often caused by genetics, poor diet, lack of exercise, stress, obesity, or underlying medical conditions like kidney disease.",
    "The hippocampus is responsible for forming and storing new memories and plays a role in learning and spatial navigation."
]

embedder = SentenceTransformer("BAAI/bge-base-en-v1.5")

def get_vram():
    if torch.cuda.is_available():
        return torch.cuda.memory_allocated() / 1024**2
    return 0

def accuracy(preds, refs):
    p_emb = embedder.encode(preds, convert_to_tensor=True)
    r_emb = embedder.encode(refs, convert_to_tensor=True)
    sims = util.cos_sim(p_emb, r_emb)
    return sims.diag().mean().item()

def benchmark_hf(model_path, label):
    tokenizer = AutoTokenizer.from_pretrained(model_path)
    model = AutoModelForCausalLM.from_pretrained(model_path, device_map=DEVICE)
    outputs = []
    start = time.time()
    for prompt in PROMPTS:
        input_ids = tokenizer(prompt, return_tensors="pt").to(DEVICE)
        out = model.generate(**input_ids, max_new_tokens=128)
        outputs.append(tokenizer.decode(out[0], skip_special_tokens=True))
    end = time.time()
    tokens = sum(len(tokenizer.encode(r)) for r in outputs)
    tps = tokens / (end - start)
    acc = accuracy(outputs, GROUND_TRUTH)
    return {"Model": label, "Tokens/sec": round(tps,2), "Latency(s)": round(end-start,2), "VRAM(MB)": round(get_vram(),2), "Accuracy": round(acc,3)}

def benchmark_gguf(label):
    llm = Llama(model_path=GGUF_MODEL, n_ctx=2048, n_threads=8, verbose=False)
    outputs = []
    start = time.time()
    for prompt in PROMPTS:
        out = llm(prompt, max_tokens=128)
        outputs.append(out["choices"][0]["text"])
    end = time.time()
    tokens = sum(len(o.split()) for o in outputs)
    tps = tokens / (end - start)
    acc = accuracy(outputs, GROUND_TRUTH)
    return {"Model": label, "Tokens/sec": round(tps,2), "Latency(s)": round(end-start,2), "VRAM(MB)": round(get_vram(),2), "Accuracy": round(acc,3)}

if __name__ == "__main__":
    os.makedirs("benchmarks", exist_ok=True)
    results = []

    for i in range(3):
        results.append(benchmark_gguf("GGUF Q8 llama.cpp"))
        results.append(benchmark_hf(BASE_MODEL, "Base Model"))
        results.append(benchmark_hf(FT_MODEL, "Fine-tuned"))

    df = pd.DataFrame(results)
    df.to_csv(RESULTS_PATH, mode='a', index=False)
    print(df)
